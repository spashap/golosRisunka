class _SafeForms(dict):
    """Неизвестный слот оставляем как есть: {name}/{age}/{band}/{mirror} подставляются
    позже и не должны ронять склонение."""

    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def g(text: str, address_form: str = "он") -> str:
    """Подставляет формы обращения. Тексты без слотов проходят насквозь."""
    return text.format_map(_SafeForms(_FORMS.get(address_form, _FORMS["он"])))


_HUSH = "жшчщгкх"   # после шипящих и заднеязычных «-а» переходит в «-и», а не в «-ы»


def genitive(name: str, address_form: str = "он") -> str:
    """Имя в родительном падеже: «портрет Софии», а не «портрет София».

    Покрывает подавляющее большинство русских имён и уменьшительных. Незнакомую
    форму (иностранное, несклоняемое) оставляем как есть: «портрет Мэй» читается
    нормально, а неправильное склонение — нет.
    """
    n = (name or "").strip()
    if not n:
        return n
    low = n.lower()
    if low.endswith("а"):
        return n[:-1] + ("и" if len(n) > 1 and low[-2] in _HUSH else "ы")
    if low.endswith("я"):
        return n[:-1] + "и"
    if low.endswith("ь"):
        # Игорь -> Игоря, но Любовь -> Любови. Различаем по обращению, как в accusative.
        return n[:-1] + ("я" if address_form == "он" else "и")
    if low.endswith("й"):
        return n[:-1] + "я"
    if low[-1] in "оеиуыэю":     # Данко, Мэри — не склоняем
        return n
    return n + "а"               # Алекс -> Алекса, Артём -> Артёма


def accusative(name: str, address_form: str = "он") -> str:
    """Имя в винительном падеже: «спросите Дашу», «это про Дашу».

    Родительный тут не годится: «спросите Даши» и «это про Даша» — обе формы неверны,
    и обе успели попасть в интерфейс. Падеж разный у разных мест, поэтому функции две.
    """
    n = (name or "").strip()
    if not n:
        return n
    low = n.lower()
    if low.endswith("а"):
        return n[:-1] + "у"
    if low.endswith("я"):
        return n[:-1] + "ю"
    if low.endswith("й"):
        return n[:-1] + "я"
    if low.endswith("ь"):
        # Игорь -> Игоря, но Любовь -> Любовь. Различаем по обращению.
        return n[:-1] + "я" if address_form == "он" else n
    if low[-1] in "оеиуыэю":
        return n
    return n + "а"


def dative(name: str, address_form: str = "он") -> str:
    """Имя в дательном падеже: «задать Даше», «задать Алексу»."""
    n = (name or "").strip()
    if not n:
        return n
    low = n.lower()
    if low.endswith("ия"):        # София -> Софии, Мария -> Марии
        return n[:-1] + "и"
    if low.endswith(("а", "я")):  # Даша -> Даше, Соня -> Соне
        return n[:-1] + "е"
    if low.endswith("й"):
        return n[:-1] + "ю"
    if low.endswith("ь"):
        return n[:-1] + ("ю" if address_form == "он" else "и")
    if low[-1] in "оеиуыэю":
        return n
    return n + "у"                # Алекс -> Алексу, Артём -> Артёму


def years(n: int) -> str:
    """3 года / 5 лет. Модель арифметике и склонению не доверяем (правило проекта)."""
    if 11 <= n % 100 <= 14:
        return "лет"
    last = n % 10
    if last == 1:
        return "год"
    if last in (2, 3, 4):
        return "года"
    return "лет"


