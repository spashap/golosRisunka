ASK_VARIANTS = ("standard", "neutral", "stopped")


def duration_label(concern_key: str, duration_key: str, address_form: str = "он") -> str:
    for d in DURATIONS:
        if d["key"] == duration_key:
            raw = DURATION_LABEL_OVERRIDES.get((concern_key, duration_key), d["label"])
            return g(raw, address_form)
    return ""


def duration_modifier(concern_key: str, duration_key: str,
                      address_form: str = "он") -> tuple[str, bool]:
    """-> (текст, применён_ли_оверрайд). Второе значение нужно free_lab --texts,
    чтобы заказчик прочитал именно переопределённые пары, а не искал их в 96 сборках."""
    override = DURATION_OVERRIDES.get((concern_key, duration_key))
    if override is not None:
        return g(override, address_form), True
    return g(DURATION_MODIFIERS.get(duration_key, ""), address_form), False


def assemble_summary(*, concern_key: str, duration_key: str | None, age: int,
                     address_form: str = "он", name: str = "") -> dict:
    """Вывод после вопросов (§5).

    Возвращает {'paragraphs': [...], 'ask_variant': str, 'override_used': bool}.
    Список абзацев, а НЕ строка: склейка внутри предложения физически невозможна.
    Никакой интерпретации здесь нет и быть не может — рисунка ещё нет.
    """
    band = age_band(age)
    paragraphs: list[str] = []
    kinds: list[str] = []
    lens_q = None
    override_used = False

    if concern_key == "neutral":
        for p in NEUTRAL_PATH:
            # Возраст спрашиваем полосой, поэтому и звучит полоса: «В 5–6 лет рисунки…».
            # Это следствие решения о полосах, а не правка авторского текста.
            paragraphs.append(g(p, address_form)
                              .replace("{age} {years}", BAND_LABELS[band]))
        return {"paragraphs": paragraphs[:-1],
                "kinds": ["path"] * (len(paragraphs) - 1),
                "lens_question": None, "ask": ASK_ANY,
                "ask_note": g(ASK_NOTES["neutral"], address_form),
                "ask_variant": "neutral", "override_used": False}

    # 1. Зеркало: тревога простыми словами + фраза про длительность.
    mirror = MIRROR.get(concern_key, "")
    mod, override_used = duration_modifier(concern_key, duration_key or "",
                                           address_form)
    first = f"Вы заметили, что {mirror}."
    paragraphs.append(f"{first} {mod}".strip() if mod else first)
    kinds.append("mirror")

    # 2. Возрастной якорь — факт о возрастном этапе, единственное, что здесь разрешено.
    paragraphs.append(g(AGE_ANCHORS[band], address_form))
    kinds.append("anchor")

    # 3. Линза — ровно ОДИН вопрос. Три пункта — это домашнее задание, и поздним
    #    вечером его никто делать не будет.
    lens = LENSES.get(concern_key)
    lens_q = g(lens, address_form) if lens else None
    if lens:
        paragraphs.append(f"{LENS_PREFIX} {lens_q}")
        kinds.append("lens")

    if concern_key == "stopped":
        for p in STOPPED_PATH:
            paragraphs.append(g(p, address_form))
        return {"paragraphs": paragraphs[:-1],
                "kinds": (kinds + ["path"] * len(STOPPED_PATH))[:len(paragraphs) - 1],
                "lens_question": lens_q, "ask": ASK_ANY,
                "ask_note": g(ASK_NOTES["stopped"], address_form),
                "ask_variant": "stopped", "override_used": override_used}

    # 4-5. Переход и действие.
    paragraphs.append(TRANSITION)
    kinds.append("transition")
    # Просьбу о рисунке отдаём ОТДЕЛЬНО: на экране она уходит под заголовок продающего
    # блока. Сам текст не меняется — меняется только его место (§5 требует, чтобы
    # строка про «обычный, не самый пугающий» стояла везде, где мы просим рисунок).
    return {"paragraphs": paragraphs, "kinds": kinds, "lens_question": lens_q,
            "ask": ASK_ANY, "ask_note": g(ASK_NOTES["standard"], address_form),
            "ask_variant": "standard", "override_used": override_used}


def wait_hint(concern_key: str, address_form: str = "он") -> str:
    """Текст экрана ожидания: его собственный вопрос, а не индикатор прогресса."""
    if concern_key == "neutral":
        body = g(WAIT_NEUTRAL, address_form)
    else:
        body = g(LENSES.get(concern_key, WAIT_NEUTRAL), address_form)
    return f"{WAIT_PREFIX} {body}"
