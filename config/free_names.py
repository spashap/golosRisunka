"""Определение обращения («он»/«она») по имени ребёнка — фремиум-поток §4.

Это ГРАММАТИЧЕСКАЯ настройка, а не анкетный «пол»: заголовок «Пол ребёнка» на странице
не используется. Для однозначных имён показываем предвыбранным с возможностью поменять
одним касанием («Миша · он · изменить»); для неоднозначных, иностранных и уменьшительных
(Саша, Женя, Валя, Мика, Бусинка) — спрашиваем.

Почему нельзя обойтись суффиксом «-а/-я → она»: Никита, Илья, Кузьма, Лёва, Гоша, Фома,
Савва, Данила, Тёма — мужские. Поэтому список исключений явный, а эвристика применяется
только к именам, которых в списках нет.

Ошибка здесь стоит одно касание (кнопка «изменить» есть всегда) — но НЕ ошибиться
приятнее, поэтому списки лучше пополнять, чем усложнять эвристику.
"""
from __future__ import annotations

import re

# Спрашиваем ЯВНО: у этих имён нет однозначного ответа, и угадывание раздражает.
AMBIGUOUS = {
    "саша", "женя", "валя", "мика", "бусинка", "шура", "слава", "сима", "ника",
}

# Мужские, оканчивающиеся на -а/-я (эвристика на них сломалась бы).
MALE_VOWEL_ENDING = {
    "никита", "илья", "кузьма", "лёва", "лева", "гоша", "фома", "савва", "данила",
    "тёма", "тема", "дима", "вова", "миша", "паша", "гриша", "серёжа", "сережа",
    "лёша", "леша", "алёша", "алеша", "андрюша", "ваня", "коля", "толя", "петя",
    "витя", "костя", "боря", "сева", "стёпа", "степа", "рома", "тима", "матвея",
    "яша", "жора", "антоша", "митя", "федя", "сеня", "арсюша", "добрыня",
    "юра", "вася", "гена", "сёма", "сема", "кеша", "тоша", "проня",
}

# Женские, оканчивающиеся НЕ на -а/-я.
FEMALE_CONSONANT_ENDING = {
    "любовь", "нинель", "адель", "рахиль", "эсфирь", "жизель", "мишель", "николь",
    "изабель", "габриэль", "сесиль",
}

_CYRILLIC = re.compile(r"^[а-яё\-\s']+$", re.IGNORECASE)


def normalize_name(name: str) -> str:
    """Нормализация для сравнения. SQLite lower() кириллицу не сворачивает —
    поэтому нормализуем в Python (тот же урок, что в app/auth.py::_norm_name)."""
    return (name or "").strip().lower().replace("ё", "е")


def detect_address_form(name: str) -> str | None:
    """-> 'он' | 'она' | None (спросить явно, без предвыбора).

    None означает «мы не знаем» — это честнее неверного предвыбора на редком
    или иностранном имени.
    """
    n = normalize_name(name)
    if not n:
        return None
    # берём первое слово: родители пишут «Маша К.», «Аня (Анна)»
    n = re.split(r"[\s,(/]+", n)[0].strip("'-")
    if not n:
        return None

    if n in {normalize_name(x) for x in AMBIGUOUS}:
        return None
    if n in {normalize_name(x) for x in MALE_VOWEL_ENDING}:
        return "он"
    if n in {normalize_name(x) for x in FEMALE_CONSONANT_ENDING}:
        return "она"
    if not _CYRILLIC.match(n):
        return None          # латиница/иностранное — спрашиваем
    if len(n) < 3:
        return None          # «Ян», «Ли» и прочее короткое — не угадываем

    if n.endswith(("а", "я")):
        return "она"
    if n.endswith(("й", "ь")):
        return None          # Валерий/Игорь vs Любовь-подобные — не рискуем
    return "он"              # оканчивается на согласную


def address_form_or_ask(name: str) -> tuple[str, bool]:
    """-> (предвыбранная форма, надо_ли_спрашивать_явно).

    Когда надо спрашивать, всё равно возвращаем 'он' как безопасный дефолт для
    рендера, но UI обязан показать вопрос, а не предвыбор.
    """
    form = detect_address_form(name)
    return (form or "он"), form is None
