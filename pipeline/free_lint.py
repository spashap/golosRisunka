r"""Линтер БЕСПЛАТНОГО разбора (фремиум-бета). Отдельный от pipeline/lint.py.

Почему нельзя просто позвать find_violations() платного линтера — три причины,
каждая ломает продукт молча:

1. ПЛАТНЫЙ REPAIR ДЕЛАЕТ УСПОКОЕНИЕ ХУЖЕ. «Это не повод для тревоги» ловится
   HEAVY_TERMS (\bтревож\w*), хеджа и атрибуции рядом нет -> платный _frame_scan
   требует «ДОБАВЬ оправу», а _REPAIR_INSTRUCTION велит добавить атрибуцию. На
   выходе «в проективной традиции считают, что это не повод для тревоги» — нарушение
   хуже исходного, и оно ПРОХОДИТ линтер. Здесь у успокоения семантика HARD: удалить.
2. ALLOWED_CONTEXTS ОТКАЛИБРОВАН НА ОТЧЁТ В 3000 СЛОВ. Окно frame-check ±200 символов,
   а весь бесплатный разбор ~1400. Блок 3 ОБЯЗАН содержать язык границы, и «не оценива»
   стоит в белом списке — в такой длине блок 3 попадает в окно блока 2 и амнистирует
   настоящее нарушение. Поэтому сканируем ПОЛЯ ПООТДЕЛЬНОСТИ и с узким белым списком.
3. «РОВНО ОДНА ГИПОТЕЗА» — это структурная проверка, а не стилистика. Раз §8 и так
   требует отдавать фразу/атрибуцию/ключ отдельно, сверяем их с прозой: фраза обязана
   встречаться в detail, атрибуция в detail не больше одной. Это же и делает
   накопленную библиотеку трактовок достоверной, а не параллельной выдумкой.

Регэкспы общего назначения берём из pipeline/lint.py — он НЕ меняется ни на строку.
"""
from __future__ import annotations

import re

from pipeline.free_schema import FreeAnalysis
from pipeline.lint import (ATTRIBUTION, HARD_BANNED, HEAVY_TERMS, HEDGE,
                           LIGHT_TERMS, WORK_REF)

FREE_LINT_VERSION = "1.0"

# --- A. УСПОКОЕНИЕ. Запрещено ВЕЗДЕ, включая блок 3. -----------------------------
# «Успокоение — тоже вывод»: диагноз в утешающую сторону, сделанный без единого
# доказательства. Обе модели в разборе брифа сломались именно на этом, одна дважды.
FREE_HARD_ALWAYS: list[tuple[str, str]] = [
    (r"не\s+повод\s+для\s+(?:тревог\w*|беспокойств\w*|волнени\w*|переживани\w*)",
     "успокоение — это вывод без доказательств; УДАЛИ фразу"),
    (r"(?:не\s+сто[ия]т|не\s+нужно|незачем)\s+(?:волноваться|беспокоиться|тревожиться|переживать)",
     "успокоение — это вывод без доказательств; УДАЛИ фразу"),
    (r"(?:это|такое|подобное)\s+(?:совершенно\s+|вполне\s+|абсолютно\s+)?нормальн\w*",
     "«это нормально» — диагноз в утешающую сторону; УДАЛИ фразу"),
    (r"(?:чаще\s+всего|обычно|как\s+правило),?\s+это\s+норм\w*",
     "«обычно это норма» — вывод без доказательств; УДАЛИ фразу"),
    (r"в\s+пределах\s+(?:возрастн\w+\s+)?нормы",
     "«в пределах нормы» — оценочный вывод; УДАЛИ фразу"),
    (r"ничего\s+(?:страшного|плохого|тревожного|необычного)",
     "успокоение; УДАЛИ фразу"),
    (r"вс[её]\s+в\s+порядке",
     "успокоение; УДАЛИ фразу"),
    (r"нет\s+(?:никаких\s+)?(?:причин|поводов)\s+для\s+"
     r"(?:тревог\w*|беспокойств\w*|волнени\w*|переживани\w*)",
     "успокоение; УДАЛИ фразу"),
    (r"(?:многие|большинство)\s+дет\w+|у\s+всех\s+дет\w+|"
     r"это\s+быва\w+\s+у\s+(?:многих|всех)",
     "«многие дети так делают» — успокоение через статистику, которой у нас нет; УДАЛИ фразу"),
]

# --- B. Отрицания-выводы. Запрещены в блоках 1-2 и в вопросе, но В БЛОКЕ 3 ЗАКОННЫ.
# АСИММЕТРИЯ — СУТЬ ПРИЁМА, НЕ ЗАБЫТЬ ПРИ ПРАВКЕ: «это не связано с настроением»
# в блоке 2 — успокоительный диагноз; «другие рисунки не скажут, связано ли это с
# настроением» в блоке 3 — честный язык границы, ради которого блок и существует.
FREE_HARD_OUTSIDE_BOUNDARY: list[tuple[str, str]] = [
    (r"не\s+связан\w*\s+с\s+(?:настроени\w*|состояни\w*|характер\w*|эмоци\w*)",
     "утверждение об ОТСУТСТВИИ связи — такой же вывод, как утверждение о связи; УДАЛИ"),
    (r"не\s+говорит\s+о\s+(?:проблем\w*|тревог\w*|наруш\w*|отклонени\w*)",
     "утверждение об отсутствии проблемы — вывод без доказательств; УДАЛИ"),
]

# --- C. Продуктовый и слоганный язык. Запрещён везде. ----------------------------
FREE_HARD_PRODUCT: list[tuple[str, str]] = [
    (r"в\s+полн\w+\s+отч[её]те|полн\w+\s+отч[её]т",
     "нельзя обещать «в полном отчёте узнаете»; УДАЛИ"),
    (r"узна\w+,?\s+что\s+это\s+значит",
     "нельзя обещать объяснение значения; УДАЛИ"),
    (r"разблокир\w*|открой\w*\s+доступ",
     "продуктовый жаргон запрещён; УДАЛИ"),
    (r"\b(?:минимальн\w+|базов\w+|пробн\w+)\s+(?:разбор\w*|версия|вариант\w*|отч[её]т\w*)",
     "слова «минимальный/базовый/пробный» в тексте для родителя запрещены — "
     "это разбор одного рисунка, одна вещь, сделанная как следует; УДАЛИ"),
    (r"богат\w+\s+(?:внутренн\w+\s+мир\w*|фантази\w*|воображени\w*)",
     "общая похвала — самый надёжный признак шаблона; УДАЛИ или замени видимой деталью"),
    (r"удивительн\w+|восхища\w+|потряса\w+|невероятн\w+",
     "суперлатив в коротком разборе читается как реклама; УДАЛИ"),
]

# --- D. «Повторяемость доказывает характер». Запрещено везде (важнее для блока 3).
FREE_HARD_REPEATABILITY: list[tuple[str, str]] = [
    (r"раз\s+за\s+разом.{0,60}?(?:это\s+про\s+н|характер|черт\w+\s+личност|говорит\s+о\s+н)",
     "повторяемость доказывает повторяемость, а не характер (§7); ПЕРЕПИШИ на "
     "«повторяется ли такой способ строить изображение или появился только здесь»"),
    (r"(?:если|раз)\b.{0,40}?повторя\w+.{0,60}?(?:значит|это\s+про\s+н|характер|"
     r"черт\w+|говорит\s+о\s+н)",
     "повторяемость доказывает повторяемость, а не характер (§7); ПЕРЕПИШИ"),
    (r"повторени\w+.{0,40}?(?:характер|черт\w+|личност\w+)",
     "повторение нельзя превращать в черту характера (§7); ПЕРЕПИШИ"),
]

# Узкий белый список: в коротком тексте широкий (как в платном линтере) амнистирует
# настоящие нарушения через соседний абзац.
FREE_ALLOWED_CONTEXTS = ["не ставим диагноз", "не диагноз", "это не диагноз"]

# Гипотезный оборот, расширенный под живой тон портретного блока: платный HEDGE
# требует «похоже НА», а в тёплой прозе естественно «Похоже, её сейчас держит…».
FREE_HEDGE = re.compile(
    HEDGE.pattern + r"|похоже,|кажется,|судя\s+по|видимо,|скорее\s+всего,|"
    r"складывается\s+(?:ощущение|впечатление)|читается\s+как|как\s+будто|"
    r"мож(?:ет|но)\s+быть", re.IGNORECASE)

# «Автор» о самом ребёнке. Допускаем ОДНО вхождение — в родовой формуле традиции
# («связывают со значимостью для автора»); больше — значит, ребёнка так и зовут.
MAX_AUTHOR_MENTIONS = 1
# Протокольные обороты, которые превращают отчёт для мамы в акт осмотра.
# Конструкция отрицания: «не как отражение состояния, а как освоение задачи».
# Чтобы отвергнуть состояние, его приходится назвать — и в голове родителя остаётся
# именно оно. Пишем, ЧТО это есть, и никогда — чего не есть.
FREE_HARD_NEGATION: list[tuple[str, str]] = [
    (r"не\s+как\s+[^.;]{0,80}?,?\s*а\s+как\s",
     "конструкция «не как X, а как Y» называет X, чтобы его отвергнуть. Напиши прямо, "
     "ЧЕМ это является, без первой половины"),
    (r"не\s+(?:отражени\w+|проявлени\w+|признак\w*|свидетельств\w+|показатель\w*)\s+"
     r"[^.;]{0,60}?,\s*а\s+",
     "утверждение через отрицание называет то, что отвергает. Напиши прямо, чем это является"),
    (r"(?:это|здесь)\s+не\s+(?:про|о)\s+[^.;]{0,50}?,\s*а\s+(?:про|о)\s",
     "«это не про X, а про Y» называет X. Напиши сразу про Y"),
]

FREE_HARD_PROTOCOL: list[tuple[str, str]] = [
    (r"человекоподобн\w+", "«человекоподобные фигуры» — это протокол осмотра, а не "
                           "текст для мамы; назови, кто изображён"),
    (r"объект\w*\s+исследовани", "канцелярит; пиши по-человечески"),
]


def _scan_list(text: str, rules: list[tuple[str, str]], where: str,
               kind: str) -> list[dict]:
    hits: list[dict] = []
    for pattern, why in rules:
        for m in re.finditer(pattern, text, re.IGNORECASE):
            s, e = max(0, m.start() - 70), min(len(text), m.end() + 70)
            ctx = text[s:e]
            if any(a in ctx.lower() for a in FREE_ALLOWED_CONTEXTS):
                continue
            hits.append({"where": where, "match": m.group(0), "why": why,
                         "context": ctx, "kind": kind})
    return hits


# Слова о состоянии, которыми вопрос ребёнку УЖЕ решает, что значит рисунок.
# Контрпример §7 — «Почему монстр такой злой?»; заметь, что «злой» не покрывается
# LIGHT_TERMS платного линтера (там только «злость»), поэтому нужен свой словарь.
QUESTION_STATE_WORDS = re.compile(
    r"\b(?:зл(?:ой|ая|ое|ые|ым)|сердит\w*|грустн\w*|печальн\w*|несчастн\w*|"
    r"страшн\w*|испуган\w*|напуган\w*|одинок\w*|обижен\w*|расстроен\w*|"
    r"агрессивн\w*|тревожн\w*|подавлен\w*|виноват\w*)", re.IGNORECASE)
# Наводящая конструкция «почему X такой Y» — тоже готовый ответ, а не вопрос.
QUESTION_LEADING = re.compile(r"почему\s+[\w\s]{0,20}?так(?:ой|ая|ое|ие)\b", re.IGNORECASE)

_CLAUSE_BREAK = re.compile(r"[.,;:!?()\n]|—|–")


def _artifact_attached(text: str, end: int, window: int) -> bool:
    """Относится ли термин к САМОЙ РАБОТЕ, а не к ребёнку.

    Платный линтер просто ищет артефакт-существительное в 40 символах после термина.
    В коротком разборе этого мало: «ребёнок тревожится: линии дрожат» получал амнистию
    из-за слова «линии» в следующей клаузе. Поэтому режем по границе клаузы —
    исключение действует только для СРАЩЁННОГО оборота («тревожное небо»,
    «настроение работы»), ради которого оно и вводилось.
    """
    frag = text[end:end + window]
    br = _CLAUSE_BREAK.search(frag)
    if br:
        frag = frag[:br.start()]
    return bool(WORK_REF.search(frag))


def _sensitive_terms(text: str, strict: bool = False) -> list[re.Match]:
    """Сенситивные термины, ОТНОСЯЩИЕСЯ К РЕБЁНКУ. Исключение для артефакта
    («тёмная гамма», «настроение работы», «тревожное небо») сохраняем."""
    window = 20 if strict else 40
    out = []
    for term_re in (HEAVY_TERMS, LIGHT_TERMS):
        for m in term_re.finditer(text):
            if _artifact_attached(text, m.end(), window):
                continue
            out.append(m)
    return out


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "").strip().lower())


def _all_text(a: FreeAnalysis) -> str:
    return "\n".join([a.opening, a.detail, a.portrait_hint,
                      a.question_to_child, a.unknown_next])


def _check_name_usage(a: FreeAnalysis, child_name: str) -> list[dict]:
    """Имя вместо «автора» — требование тона, но проверяется механически.

    Считаем «автор» по всему тексту и требуем, чтобы имя ребёнка встречалось хотя бы
    дважды. Порог именно такой, потому что одно вхождение «автора» законно внутри
    родовой формулы традиции, а имя, названное один раз, — это подпись, а не обращение.
    """
    hits: list[dict] = []
    text = _all_text(a)
    for pattern, why in FREE_HARD_PROTOCOL:
        hits += _scan_list(text, [(pattern, why)], "tone", "text")
    n_author = len(re.findall(r"\bавтор\w*", text, re.IGNORECASE))
    if n_author > MAX_AUTHOR_MENTIONS:
        hits.append({
            "where": "tone", "match": f"«автор» x{n_author}", "kind": "text",
            "context": text[:160],
            "why": "не называй ребёнка «автором» — это самое холодное слово, которым "
                   "можно назвать ребёнка. Используй имя",
        })
    if child_name:
        first = re.split(r"[\s.,]+", child_name.strip())[0]
        if len(first) >= 3:
            n_name = len(re.findall(re.escape(first[:-1]), text, re.IGNORECASE))
            if n_name < 2:
                hits.append({
                    "where": "tone", "match": f"имя встречается {n_name} раз",
                    "kind": "text", "context": text[:160],
                    "why": f"имя «{first}» должно звучать в тексте минимум дважды — "
                           f"это разбор для мамы, а не карточка объекта",
                })
    return hits


def find_free_violations(a: FreeAnalysis, child_name: str = "") -> list[dict]:
    """Нарушения в бесплатном разборе. kind: 'text' — чинится переписыванием,
    'hypothesis' — можно снять даунгрейдом (выбросить гипотезу)."""
    hits: list[dict] = []
    common = (FREE_HARD_ALWAYS + FREE_HARD_PRODUCT + FREE_HARD_REPEATABILITY
              + FREE_HARD_NEGATION)

    # --- блок 1: тёплое открытие. Диагноз и успокоение запрещены, но строгий запрет
    # на любое тёплое слово снят (шаг 4): холодный протокол осмотра — это брак,
    # а не безопасность.
    hits += _scan_list(a.opening, common + FREE_HARD_OUTSIDE_BOUNDARY, "opening", "text")
    hits += _scan_list(a.opening, HARD_BANNED, "opening", "text")
    # Тепло — да, голое утверждение о состоянии — нет. «Видно, что ребёнок тревожится»
    # в открытии остаётся диагнозом, сколько бы тёплых слов вокруг ни стояло.
    for m in _sensitive_terms(a.opening, strict=True):
        heavy_here = bool(HEAVY_TERMS.match(m.group(0)))
        if heavy_here or not FREE_HEDGE.search(a.opening):
            hits.append({
                "where": "opening", "match": m.group(0), "kind": "text",
                "context": a.opening[max(0, m.start() - 70):m.end() + 70],
                "why": ("тяжёлое состояние ребёнка в открытии недопустимо — опиши "
                        "видимое" if heavy_here else
                        "состояние ребёнка в открытии — только через гипотезный "
                        "оборот, либо опиши видимую деталь"),
            })

    # --- блок 3: короткий портрет. Интерпретационный по определению, поэтому здесь
    # нужна ОПРАВА (гипотезный оборот), а не запрет.
    hits += _scan_list(a.portrait_hint, common, "portrait_hint", "text")
    hits += _scan_list(a.portrait_hint, HARD_BANNED, "portrait_hint", "text")
    heavy = [m for m in _sensitive_terms(a.portrait_hint) if HEAVY_TERMS.match(m.group(0))]
    if _sensitive_terms(a.portrait_hint) and not FREE_HEDGE.search(a.portrait_hint):
        hits.append({
            "where": "portrait_hint", "match": "(портрет без гипотезного оборота)",
            "kind": "text", "context": a.portrait_hint,
            "why": "портрет говорит о ребёнке — нужен гипотезный оборот («похоже», "
                   "«кажется», «может говорить о»). Не убирай тепло, добавь оправу",
        })
    if heavy and not ATTRIBUTION.search(a.portrait_hint):
        hits.append({
            "where": "portrait_hint", "match": heavy[0].group(0), "kind": "text",
            "context": a.portrait_hint,
            "why": "тяжёлый термин о состоянии ребёнка в портрете требует ещё и "
                   "атрибуции к традиции — либо смягчи формулировку",
        })

    # --- «автор» вместо имени: самое холодное слово для четырёхлетнего ребёнка.
    # Разрешаем ОДНО вхождение — в родовой формуле традиции («значимость для автора»),
    # но не как способ называть самого ребёнка.
    hits += _check_name_usage(a, child_name)

    # --- блок 2 ---
    hits += _scan_list(a.detail, common + FREE_HARD_OUTSIDE_BOUNDARY, "detail", "text")
    hits += _scan_list(a.detail, HARD_BANNED, "detail", "text")

    # --- вопрос ребёнку ---
    hits += _scan_list(a.question_to_child, common + FREE_HARD_OUTSIDE_BOUNDARY,
                       "question_to_child", "text")
    hits += _scan_list(a.question_to_child, HARD_BANNED, "question_to_child", "text")
    # Вопросительный знак должен БЫТЬ, но не обязан быть последним символом: по
    # контракту шага 4 за вопросом идёт ещё фраза про то, что ответ ребёнка точнее
    # догадки взрослого.
    if "?" not in a.question_to_child:
        hits.append({"where": "question_to_child", "match": a.question_to_child[-40:],
                     "kind": "text", "context": a.question_to_child,
                     "why": "блок должен содержать сам вопрос ребёнку со знаком «?»"})
    for m in list(_sensitive_terms(a.question_to_child, strict=True)) \
            + list(QUESTION_STATE_WORDS.finditer(a.question_to_child)):
        hits.append({
            "where": "question_to_child", "match": m.group(0), "kind": "text",
            "why": "вопрос со словом о состоянии («злой», «грустный») уже решил, что "
                   "значит рисунок. Спроси открыто: «расскажи, кто это и что здесь "
                   "сейчас происходит?»",
            "context": a.question_to_child,
        })
    if QUESTION_LEADING.search(a.question_to_child):
        hits.append({
            "where": "question_to_child", "match": a.question_to_child[:60],
            "kind": "text", "context": a.question_to_child,
            "why": "«почему … такой …» — наводящая конструкция: она уже содержит ответ. "
                   "Спроси открыто, без подсказанных вариантов",
        })

    # --- блок 3: язык границы законен, успокоение — нет ---
    hits += _scan_list(a.unknown_next, common, "unknown_next", "text")
    hits += _scan_list(a.unknown_next, HARD_BANNED, "unknown_next", "text")

    # --- структурная проверка «ровно одна гипотеза» ---
    hits += _check_hypothesis(a)
    return hits


def _check_hypothesis(a: FreeAnalysis) -> list[dict]:
    hits: list[dict] = []
    detail = a.detail

    if a.hypothesis is None:
        # Контракт §7 «законной гипотезы нет»: тогда её нет и в прозе — иначе модель
        # отдала бы трактовку родителю, но не отдала в библиотеку §8, худший из миров.
        #
        # НО маркер протащенной трактовки — именно АТРИБУЦИЯ к традиции, а не хедж.
        # После разворота на продажу «похоже, ему нравится закрашивать плотно» — это
        # осторожное наблюдение о поведении, а не проективная трактовка, и запрещать
        # его значит возвращать мёртвый тон. Тяжёлые термины о ребёнке ловим отдельно.
        if ATTRIBUTION.search(detail):
            hits.append({
                "where": "detail", "match": "(атрибуция при hypothesis=null)",
                "kind": "hypothesis", "context": detail,
                "why": "в тексте есть ссылка на традицию, но гипотеза не оформлена. "
                       "Либо ОФОРМИ её как hypothesis с ключом из словаря, либо УБЕРИ "
                       "отсылку к традиции и оставь наблюдение",
            })
        heavy_free = [m for m in _sensitive_terms(detail)
                      if HEAVY_TERMS.match(m.group(0))]
        if heavy_free:
            hits.append({
                "where": "detail", "match": heavy_free[0].group(0),
                "kind": "hypothesis", "context": detail,
                "why": "тяжёлый термин о состоянии ребёнка без оформленной гипотезы — "
                       "смягчи формулировку или оформи трактовку в полной оправе",
            })
        return hits

    phrase = a.hypothesis.phrase
    if _norm(phrase) not in _norm(detail):
        hits.append({
            "where": "hypothesis.phrase", "match": phrase[:80], "kind": "hypothesis",
            "context": detail,
            "why": "phrase обязана встречаться в detail ДОСЛОВНО — иначе библиотека "
                   "трактовок описывает не то, что прочитал родитель",
        })
    if not HEDGE.search(phrase):
        hits.append({
            "where": "hypothesis.phrase", "match": phrase[:80], "kind": "hypothesis",
            "context": phrase,
            "why": "нет гипотезного оборота — добавь «может говорить о», «иногда "
                   "связывают с», «можно прочитать как»",
        })
    if not (ATTRIBUTION.search(phrase) or ATTRIBUTION.search(detail)):
        hits.append({
            "where": "hypothesis.phrase", "match": phrase[:80], "kind": "hypothesis",
            "context": detail,
            "why": "нет атрибуции — отнеси к традиции: «в традиции прочтения детского "
                   "рисунка это иногда связывают с…». Источники не выдумывай",
        })
    if len(ATTRIBUTION.findall(detail)) > 1:
        hits.append({
            "where": "detail", "match": "(две атрибуции)", "kind": "hypothesis",
            "context": detail,
            "why": "вторая атрибуция — это вторая гипотеза. Оставь РОВНО ОДНУ: несколько "
                   "конкурирующих трактовок выглядят уклончиво для мамы",
        })
    hits += _scan_list(phrase, FREE_HARD_ALWAYS + FREE_HARD_PRODUCT,
                       "hypothesis.phrase", "hypothesis")
    return hits


def can_downgrade(hits: list[dict]) -> bool:
    """Все оставшиеся нарушения снимаются снятием гипотезы?"""
    return bool(hits) and all(h.get("kind") == "hypothesis" for h in hits)


def drop_hypothesis(a: FreeAnalysis) -> FreeAnalysis | None:
    """Даунгрейд вместо провала (§7: «если законной гипотезы нет — её нет», и это
    полноценный исход). Убираем объект гипотезы и предложение с ней из detail.
    Возвращаем None, если после удаления от блока 2 ничего не осталось — тогда
    честнее пересгенерировать, чем отдать обрубок."""
    if a.hypothesis is None:
        return None
    phrase_n = _norm(a.hypothesis.phrase)
    kept = [s for s in re.split(r"(?<=[.!?])\s+", a.detail.strip())
            if phrase_n not in _norm(s) and not ATTRIBUTION.search(s)]
    detail = " ".join(kept).strip()
    if len(re.findall(r"[^\W\d_]+", detail, re.UNICODE)) < 12:
        return None
    return a.model_copy(update={"detail": detail, "hypothesis": None})


